import 'dart:convert';
import 'dart:io';
import 'dart:ui';

import 'package:flutter_test/flutter_test.dart';
import 'package:libmonet/shapes/material_expressive_shape.dart';

import 'safe_interior.dart';

void main() {
  test('precompute endpoint-safe Material shape interiors', () {
    final options = jsonDecode(
      Platform.environment['MONET_SAFE_AREAS_OPTIONS'] ??
          (throw StateError(
            'Run dart tool/precompute_safe_areas.dart instead',
          )),
    ) as Map<String, dynamic>;
    final ratios = (options['ratios'] as List).cast<num>();
    final clearance = (options['clearance'] as num).toDouble();
    final tolerance = (options['tolerance'] as num).toDouble();
    final entries = <Map<String, Object?>>[];
    for (final shape in MaterialExpressiveShape.values) {
      final outline = SafeInteriorOutline(shape.polygon.cubics);
      entries.add({
        'shape': shape.name,
        'areaCentroid': [outline.areaCentroid.dx, outline.areaCentroid.dy],
        'rectangles': [
          for (final ratio in ratios)
            (() {
              final Rect? rect;
              try {
                rect = outline.find(
                  aspectRatio: ratio.toDouble(),
                  clearance: clearance,
                  tolerance: tolerance,
                );
              } on StateError catch (error) {
                throw StateError(
                  '${shape.name} ratio=$ratio: ${error.message}',
                );
              }
              return {
                'aspectRatio': ratio,
                'rect': rect == null
                    ? null
                    : [rect.left, rect.top, rect.right, rect.bottom],
              };
            })(),
        ],
      });
    }
    final output = File(options['output'] as String);
    output.parent.createSync(recursive: true);
    output.writeAsStringSync(
      '${const JsonEncoder.withIndent('  ').convert({
        'schemaVersion': 3,
        'generator': 'tool/precompute_safe_areas.dart',
        'source': 'androidx_graphics_shapes MaterialShapes via MaterialExpressiveShape',
        'coordinates': 'Original package unit coordinates; no bounds renormalization',
        'objective': 'Largest freely translated axis-aligned rectangle at each aspect ratio',
        'tieBreak': 'Within numerical tolerance, nearest center to exact cubic area centroid',
        'rectFormat': ['left', 'top', 'right', 'bottom'],
        'clearance': clearance,
        'tolerance': tolerance,
        'numericGuard': SafeInteriorOutline.numericGuard,
        'method': 'Lipschitz branch-and-bound over center; monotonic size bisection; recursive cubic control bounds depth 24; inconclusive rejected',
        'scope': 'Static endpoints only; no intermediate morph containment required',
        'shapes': entries,
      })}\n',
    );
    final dartOutput = options['dartOutput'] as String?;
    if (dartOutput != null) {
      final buffer = StringBuffer(
        '// Generated by tool/precompute_safe_areas.dart; do not edit.\n'
        '// Static endpoint interiors, clearance $clearance source units, '
        'global tolerance $tolerance.\n'
        "import 'dart:ui';\n"
        "import '../material_expressive_shape.dart';\n\n"
        'const materialShapeSafeAreaData = <MaterialExpressiveShape, List<Rect>>{\n',
      );
      for (final shape in entries) {
        buffer.writeln('  MaterialExpressiveShape.${shape['shape']}: [');
        for (final entry in shape['rectangles']! as List) {
          final rect = entry['rect'] as List<double>?;
          if (rect != null) {
            buffer.writeln('    Rect.fromLTRB(${rect.join(', ')}),');
          }
        }
        buffer.writeln('  ],');
      }
      buffer.writeln('};');
      final dartFile = File(dartOutput);
      dartFile.parent.createSync(recursive: true);
      dartFile.writeAsStringSync(buffer.toString());
    }
    // ignore: avoid_print
    print(
      'Wrote ${entries.length} shapes × ${ratios.length} ratios to ${output.path}',
    );
  });
}
